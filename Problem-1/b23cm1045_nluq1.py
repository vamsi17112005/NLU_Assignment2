def cosine_similarity(a, b):
    return np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b) + 1e-9)

def nearest_neighbors(word, W1, top_k=5):
    """
    For a given word, we find the most similar words in the embedding space.
    This helps us check whether the model has learned meaningful relationships.
    """

    # If word is not present in vocabulary, return safely
    if word not in word2idx:
        return f"{word} not in vocabulary"

    # Get embedding vector of the target word
    vec = W1[word2idx[word]]

    similarities = []

    # Compare this word with every other word in vocabulary
    for w in vocab:

        # Skip comparing the word with itself
        if w == word:
            continue

        # Compute similarity
        sim = cosine_similarity(vec, W1[word2idx[w]])

        similarities.append((w, sim))

    # Sort words based on similarity (highest first)
    similarities.sort(key=lambda x: x[1], reverse=True)

    # Return top-k most similar words
    return similarities[:top_k]

def analogy(a, b, c, W1):
    """
    Analogy task tries to solve: a : b :: c : ?

    We compute:
    vector(b) - vector(a) + vector(c)

    This gives a new vector, and we find the closest word to it.
    This tests whether the model has learned semantic relationships.
    """

    # Check if all words exist
    if a not in word2idx or b not in word2idx or c not in word2idx:
        return "One or more words not in vocabulary"

    # Compute analogy vector
    vec = W1[word2idx[b]] - W1[word2idx[a]] + W1[word2idx[c]]

    best_word = None
    best_score = -1

    # Search best matching word
    for w in vocab:

        # Skip input words (important)
        if w in [a, b, c]:
            continue

        score = cosine_similarity(vec, W1[word2idx[w]])

        if score > best_score:
            best_score = score
            best_word = w

    return best_word

