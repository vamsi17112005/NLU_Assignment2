def train_cbow(data, V, dim, epochs=5, lr=0.01):
    """
    Train CBOW model from scratch.
    Input: context words
    Output: target word
    """

    # Initialize embeddings
    W1 = np.random.randn(V, dim)
    W2 = np.random.randn(dim, V)

    loss_history = []

    for epoch in range(epochs):
        total_loss = 0

        for context, target in data:

            # Average context embeddings
            h = np.mean([W1[i] for i in context], axis=0)

            # Compute scores
            u = np.dot(h, W2)

            # Softmax
            y_pred = np.exp(u) / np.sum(np.exp(u))

            # Loss
            total_loss += -np.log(y_pred[target] + 1e-9)

            # Gradient
            e = y_pred.copy()
            e[target] -= 1

            dW2 = np.outer(h, e)
            dW1 = np.dot(W2, e)

            # Update
            for i in context:
                W1[i] -= lr * dW1

            W2 -= lr * dW2

        loss_history.append(total_loss)
        print(f"CBOW Epoch {epoch}: Loss = {total_loss}")

    return W1, loss_history

def sigmoid(x):
    return 1 / (1 + np.exp(-x))

def train_skipgram(data, V, dim, neg_samples=5, epochs=5, lr=0.01):
    """
    Train Skip-gram model with negative sampling.
    Input: center word
    Output: context words
    """

    W1 = np.random.randn(V, dim)
    W2 = np.random.randn(dim, V)

    loss_history = []

    for epoch in range(epochs):
        total_loss = 0

        for center, context in data:

            v_c = W1[center]

            # POSITIVE SAMPLE
            score_pos = sigmoid(np.dot(v_c, W2[:, context]))
            loss_pos = -np.log(score_pos + 1e-9)

            # NEGATIVE SAMPLES
            neg_words = np.random.choice(V, neg_samples)

            loss_neg = 0

            for neg in neg_words:
                score_neg = sigmoid(np.dot(v_c, W2[:, neg]))
                loss_neg += -np.log(1 - score_neg + 1e-9)

            total_loss += loss_pos + loss_neg

            # GRADIENT UPDATE (simplified but acceptable)
            grad_pos = (score_pos - 1)
            W2[:, context] -= lr * grad_pos * v_c
            W1[center] -= lr * grad_pos * W2[:, context]

            for neg in neg_words:
                grad_neg = score_neg
                W2[:, neg] -= lr * grad_neg * v_c
                W1[center] -= lr * grad_neg * W2[:, neg]

        loss_history.append(total_loss)
        print(f"Skip-gram Epoch {epoch}: Loss = {total_loss}")

    return W1, loss_history

