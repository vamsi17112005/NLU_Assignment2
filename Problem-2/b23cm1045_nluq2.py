import torch
import torch.nn as nn


class CharRNN(nn.Module):

    def __init__(self, vocab_size, hidden_size):
        super(CharRNN, self).__init__()

        # Store hidden size for later use
        self.hidden_size = hidden_size

        # Embedding layer converts character indices into dense vectors
        self.embedding = nn.Embedding(vocab_size, hidden_size)

        # Basic RNN layer
        self.rnn = nn.RNN(hidden_size, hidden_size, batch_first=True)

        # Fully connected layer to predict next character
        self.fc = nn.Linear(hidden_size, vocab_size)

    def forward(self, x, hidden):
        # Convert indices → embeddings
        x = self.embedding(x)
        out, hidden = self.rnn(x, hidden)

        # Convert hidden states → output predictions
        out = self.fc(out)

        return out, hidden

    def init_hidden(self, batch_size):
        # Initialize hidden state with zeros
        return torch.zeros(1, batch_size, self.hidden_size)

hidden_size = 128

model = CharRNN(vocab_size, hidden_size)

# Loss function (used for classification)
criterion = nn.CrossEntropyLoss()

optimizer = torch.optim.Adam(model.parameters(), lr=0.003)

epochs = 5
for epoch in range(epochs):
    total_loss = 0

    for name in encoded_names:
        # Input = all chars except last
        # Target = all chars except first
        input_seq = torch.tensor(name[:-1]).unsqueeze(0)
        target_seq = torch.tensor(name[1:]).unsqueeze(0)

        # Initialize hidden state
        hidden = model.init_hidden(1)

        # Reset gradients
        optimizer.zero_grad()

        # Forward pass
        output, hidden = model(input_seq, hidden)

        # Compute loss
        loss = criterion(output.squeeze(), target_seq.squeeze())

        # Backpropagation
        loss.backward()
        optimizer.step()
        total_loss += loss.item()

    print(f"Epoch {epoch+1}, Loss: {total_loss:.4f}")

import random

# Function to generate a name from trained model
def generate_name(model, start_char, length=10):

    model.eval()

    # Start with given character
    input_char = torch.tensor([[char_to_idx[start_char]]])
    hidden = model.init_hidden(1)

    name = start_char

    for _ in range(length):
        output, hidden = model(input_char, hidden)

        # Convert output to probabilities
        probs = torch.softmax(output[0, -1], dim=0).detach().numpy()

        # Randomly pick next character
        idx = random.choices(range(vocab_size), weights=probs)[0]

        char = idx_to_char[idx]
        name += char

        input_char = torch.tensor([[idx]])

    return name


