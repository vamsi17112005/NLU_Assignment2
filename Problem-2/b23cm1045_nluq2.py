import torch
import torch.nn as nn

class CharBLSTM(nn.Module):

    def __init__(self, vocab_size, hidden_size):
        super(CharBLSTM, self).__init__()

        self.hidden_size = hidden_size

        # Each character → dense vector
        self.embedding = nn.Embedding(vocab_size, hidden_size)

        # Bidirectional LSTM (forward + backward)
        self.lstm = nn.LSTM(
            input_size=hidden_size,
            hidden_size=hidden_size,
            batch_first=True,
            bidirectional=True
        )

        # Since bidirectional → output size = 2 * hidden_size
        self.fc = nn.Linear(hidden_size * 2, vocab_size)

    def forward(self, x, hidden):

        # Convert indices → embeddings
        x = self.embedding(x)

        # Pass through BLSTM
        out, hidden = self.lstm(x, hidden)

        # Predict next character
        out = self.fc(out)

        return out, hidden

    def init_hidden(self, batch_size):
        # Initialize hidden + cell states (2 directions)
        return (
            torch.zeros(2, batch_size, self.hidden_size),
            torch.zeros(2, batch_size, self.hidden_size)
        )

