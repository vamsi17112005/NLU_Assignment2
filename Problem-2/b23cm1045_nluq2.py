import torch
import random

def generate_name_blstm(model, start_char="A", max_len=15, temperature=0.7):

    model.eval()

    name = start_char
    current_char = start_char

    for _ in range(max_len):

        # Reinitialize hidden state each step (important for BLSTM)
        hidden = model.init_hidden(1)

        input_char = torch.tensor([[char_to_idx[current_char]]])

        output, hidden = model(input_char, hidden)

        logits = output[0, -1] / temperature
        probs = torch.softmax(logits, dim=0)

        #  Repetition penalty
        for ch in set(name[-3:]):  # last 3 chars
            if ch in char_to_idx:
                probs[char_to_idx[ch]] *= 0.5

        probs = probs / probs.sum()  # normalize

        idx = torch.multinomial(probs, 1).item()
        char = idx_to_char[idx]

        # Stop if newline OR name is already reasonable length
        if char == '\n' or len(name) > 6:
            break

        name += char
        current_char = char

    return name

