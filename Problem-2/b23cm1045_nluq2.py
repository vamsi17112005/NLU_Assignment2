# Novelty Rate measures how many generated names are completely new,
# i.e., not present in the training dataset.

def novelty_rate(generated, training_set):

    new_names = 0

    for name in generated:
        if name not in training_set:
            new_names += 1

    # Return percentage of new (unseen) names
    return (new_names / len(generated)) * 100

# Diversity measures how varied the generated names are.
# It is simply the ratio of unique names to total generated names.

def diversity(generated):

    unique_names = set(generated)

    return len(unique_names) / len(generated)

